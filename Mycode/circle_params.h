#ifndef __CIRCLE_PARAMS_H
#define __CIRCLE_PARAMS_H

/* ============================================================================
   ★★★ 定半径圆周运动 —— 所有可调参数集中表（改这里 → 重新编译即生效）★★★

   ============================================================================
   【分步调试指南】用串口指令 "cstage i N" 在线切换调试阶段（N=0~4），
   从简到繁逐级打开，每级只调该级新增的 1~3 个参数，调好再进下一级：
   ----------------------------------------------------------------------------
   stage 0 = 纯开环            ：只走"切向速度前馈 v_x + 角速度前馈 w"，
                                 不读测距、距离环/航向环/漂移修正全部关闭。
                                 验证点：① 绕圈方向对不对（反了把 CIRCLE_Run
                                 最后一个参数 1 和 -1 互换）；② 切向与角速度比例
                                 合不合适（车应该能勉强绕大半圈不跑飞）。
                                 本级需要调的参数：无（几何常量除外）。
   stage 1 = 开环 + 测距       ：开始读测距/低通滤波/串口打印，但 v_y 仍为 0、
                                 w 仍是开环前馈。圈还是可能不圆（正常）。
                                 验证点：SerialPlot 里 d 曲线是否平稳、无杂散
                                 大跳变。本级需要调的参数：calpha / cdmin / cdmax。
   stage 2 = + 径向距离环       ：v_y 由距离环 PID 输出，开始真正保半径。
                                 验证点：d 曲线被拉回目标、半径误差收敛、无振荡。
                                 本级需要调的参数：ckp / cki / ckd / cvy。
   stage 3 = + 航向同步环       ：w = ω前馈 + 角度环Δω，车头始终对准圆心。
                                 验证点：d 曲线更平稳、圈明显更圆、车头不歪。
                                 本级需要调的参数：cyawkp / cw。
   stage 4 = + 漂移修正         ：极值搜索微调航向目标（正对管壁测距最小）。
                                 验证点：连续多圈半径也不漂、越绕越稳定。
                                 本级需要调的参数：cstep / cdriftper。
   ----------------------------------------------------------------------------
   调参口诀：先 P（ckp）→ 加 D（ckd）压振荡 → 加 I（cki）消稳态误差 →
           再开航向环（cyawkp）→ 最后开漂移修正（cstep）。
   ============================================================================ */

/* ============================================================================
   0. 几何常量（按实际车量，一般不用动；不准只会导致整体半径偏大/偏小，
      不会影响"圆不圆"）
   ============================================================================ */
#define CIRCLE_SENSOR_OFFSET_CM  8.0f   /* 测距传感器到车中心的纵向距离(cm)
                                           调大→车中心到管心实际半径被算大
                                           调小→实际半径被算小
                                           实测准了就 0 误差，一次性量准即可 */

#define CIRCLE_PIPE_RADIUS_CM    4.0f   /* 水管外径半径(cm)，本规则场地柱径 8cm→4cm
                                           同上，量准即可 */

/* ============================================================================
   1. 调试阶段 stage（串口指令 cstage i 2 可在线切换，立即生效）
   ============================================================================ */
#define CIRCLE_STAGE_DEF   0          /* 当前调试阶段 0~4，见顶部指南
                                          0=纯开环 1=+测距 2=+距离环 3=+航向环 4=+漂移
                                          调大→环开得越多、越接近最终效果
                                          调小→越简单、好定位是哪一环的问题 */

/* ============================================================================
   2. 径向距离环 PID（stage>=2 生效；串口调参名 ckp/cki/ckd/cvy）
      —— 作用：测距实际半径比目标大→车前进靠近管、小→后退远离管，保半径恒定
   ============================================================================ */
#define CIRCLE_DIST_KP_DEF    0.50f  /* 距离环比例增益：半径偏差 1cm → 产生多少 cm/s 径向速度
                                          调大→半径拉回快、圈更贴目标半径
                                            但太大→修正过猛、车向管猛插/后退，圈变形、振荡
                                          调小→修正柔和、不易振荡
                                            但太小→半径飘远了拉不回来，圆变大或变小
                                          建议从 0.3 起步，每次 ±0.1 */

#define CIRCLE_DIST_KI_DEF    0.08f  /* 距离环积分增益：消"半径差一小截一直补不回来"的稳态误差
                                          调大→长时间偏小半径被慢慢补回，半径更精确
                                            但太大→积分超调，绕圈中半径周期性摆动
                                          调小→积分作用弱、几乎不管
                                            但 0 也基本能转，只是允许一点常值半径偏差
                                          建议 P 调稳后若 d 曲线整体偏一个值再慢慢加 */

#define CIRCLE_DIST_KD_DEF    0.10f  /* 距离环微分增益：预测半径变化趋势提前刹车，压振荡
                                          调大→超调被压住、更稳
                                            但太大→对测距噪声放大、输出抖
                                          调小→0 时靠 P 也能收敛，只是可能有一点来回摆动
                                          建议 P 调好后若 d 曲线在目标附近来回摆再加 */

#define CIRCLE_DIST_INT_MAX_DEF 300.0f /* 距离环积分限幅
                                          调大→积分能存更多、补偿更强，但太大→积分饱和猛冲
                                          调小→积分被早早截断、补偿弱，太小→积分几乎不工作 */

#define CIRCLE_VY_MAX_DEF     8.0f   /* 径向修正速度上限(cm/s)
                                          调大→大偏差时能快速拉回半径
                                            但太大→猛插圈、轨迹波动大
                                          调小→修正动作柔和
                                            但太小→大偏差时拉回慢，可能撞管或跑远
                                          建议 = 切向速度的一半左右即可 */

/* ============================================================================
   3. 航向同步环（stage>=3 生效；串口调参名 cyawkp/cw）
      —— 作用：w = ω前馈 + Δω，Δω 把车头始终扳向"指向圆心"，防止测距变斜距
   ============================================================================ */
#define CIRCLE_YAW_KP_DEF    (-0.03f)/* 航向同步环比例：车头与目标航向偏差 1° → 附加角速度
                                          注意：必须为负（陀螺仪 yaw 顺时针为正、w 逆时针为正，镜像）
                                          调大(更负)→车头跟得紧、始终对准圆心、d 更稳
                                            但太大→车头来回摆动、d 抖动
                                          调小(接近0)→车头跟得松、慢慢歪掉
                                            歪久了测距变斜距、d 变大，恶性循环圈不圆
                                          建议从 -0.02 起步，每次 ±0.005 */

#define CIRCLE_W_MAX_DEF     2.8f   /* w 总输出限幅(rad/s)，与整车航向环限幅一致
                                          调大→大圈高速时转向足够，但太大→转向猛
                                          调小→转向温和，但太小→高速大圈时转不过来、圈变大 */

/* ============================================================================
   4. 测距滤波 / 有效性（stage>=1 生效；串口调参名 calpha，cdmin/cdmax 改这里）
      —— 作用：测距噪声靠低通滤波压掉；无效值(杂散/测空)直接丢弃、保持上次值
   ============================================================================ */
#define CIRCLE_FILTER_ALPHA_DEF 0.80f /* 测距一阶低通滤波系数(0~1)，越接近 1 越平滑
                                          调大→曲线越平滑、距离环越稳
                                            但太大→响应慢、修正滞后、半径拉回慢
                                          调小→响应快、跟手
                                            但太小→噪声大、距离环被带得乱抖
                                          建议 0.7~0.9，先 0.8 看 SerialPlot 再调 */

#define CIRCLE_D_VALID_MIN_DEF 50    /* 测距有效下限(mm)：读数小于它 → 视为杂散，保持上次滤波值
                                          调大→更多小值被丢弃，防近距离杂散
                                            但太大→真实近距离信号也被丢、距离环失效
                                          调小→允许更小读数
                                            但太小→杂散小值混进来、距离环被吓到猛动 */

#define CIRCLE_D_VALID_MAX_DEF 250   /* 测距有效上限(mm)：读数大于它 → 视为测空/丢目标，保持上次滤波值
                                          调大→测空时也用上次值、更抗丢目标
                                            但太大→真测空大值进来、距离环误以为很远猛往前插
                                          调小→测空更快被识别丢弃
                                            但太小→目标偏远些的正常读数也被丢 */

/* ============================================================================
   5. 极值搜索漂移修正（stage==4 生效；串口调参名 cstep，driftper 改这里）
      —— 作用：陀螺仪长期积分会漂，车头会慢慢歪导致测距变斜距。
              "正对管壁时测距最小"，每隔一小段时间给航向目标一个微小步长，
              测距变小→方向对保持，变大→反向（爬山法），把车头慢慢扳回正对管壁。
   ============================================================================ */
#define CIRCLE_DRIFT_STEP_DEF 0.20f  /* 每次漂移修正的航向微调量(°)
                                          调大→漂移纠得快
                                            但太大→车头被反复顶来顶去、d 波动
                                          调小→更稳
                                            但太小→纠不过来、时间长了车头还是慢慢歪
                                          建议 0.1~0.3，慢速绕圈用 0.2 即可 */

#define CIRCLE_DRIFT_PERIOD_DEF 200  /* 漂移修正周期(ms)
                                          调大→修正间隔长、干扰距离环少
                                            但太大→漂移纠得太慢
                                          调小→纠得更勤
                                            但太小→频繁微调航向、反而干扰距离环 */

/* ============================================================================
   6. 调试打印（串口调参名 cprint，0 关闭）
   ============================================================================ */
#define CIRCLE_PRINT_PERIOD_DEF 200  /* 绕圈状态串口打印周期(ms)，0=关闭
                                          打印 8 通道：d 滤波测距 / D 实际半径 /
                                          eD 半径误差 / vx vy w / yawT 目标航向 / yaw 实际
                                          调小→打印密、看曲线细，但刷屏快
                                          调大→打印稀、省串口，调完参数后建议改 0 */

#endif /* __CIRCLE_PARAMS_H */


